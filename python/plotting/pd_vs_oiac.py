def build_controller_plot(controller_data: dict[str, dict[Terrain, list[float]]]):
    """
    @brief Build controller plot.
    @param controller_data:
    @return
    """
    base_size = 25
    plt.rcParams.update({
        'font.size': base_size,        # Default text size
        'axes.titlesize': base_size + 5,   # Title size
        'axes.labelsize': base_size + 4,   # X and Y label size
        'xtick.labelsize': base_size + 2,  # X tick size
        'ytick.labelsize': base_size + 2,  # Y tick size
        'legend.fontsize': base_size + 2   # Legend size
    })
    fig, ax = plt.subplots(figsize=(12, 6))

    x = np.arange(len(CONTROLLER_ORDER))
    bar_width = 0.6
    terrain_colors = plt.get_cmap("viridis")(np.linspace(0.2, 0.85, len(TERRAIN_ORDER)))

    for controller_index, controller_name in enumerate(CONTROLLER_ORDER):
        bottom = 0.0

        for terrain_index, terrain in enumerate(TERRAIN_ORDER):
            controller_samples = controller_data.get(controller_name, {})
            terrain_samples = controller_samples.get(terrain, [])

            if not terrain_samples:
                continue

            values = np.asarray(terrain_samples, dtype=float)
            mean_value = float(np.mean(values))
            error_value = float(np.std(values, ddof=1)) if values.size > 1 else 0.0

            ax.bar(
                x[controller_index],
                mean_value,
                width=bar_width,
                bottom=bottom,
                yerr=error_value,
                capsize=4,
                color=terrain_colors[terrain_index],
                edgecolor="white",
                linewidth=0.8,
                alpha=0.95,
                label=terrain.value if controller_index == 0 else None,
            )
            bottom += mean_value

    ax.set_xticks(x)
    ax.set_xticklabels([CONTROLLER_LABELS[name] for name in CONTROLLER_ORDER])
    ax.set_ylabel("CoT")
    ax.set_xlabel("")
    ax.set_title("PD vs OIAC CoT Comparison Across Terrains")
    ax.grid(True, axis="y", alpha=0.3)
    ax.legend(title="Terrain", ncol=2)
    plt.tight_layout()

    return fig, ax


def print_controller_averages(controller_data: dict[str, dict[Terrain, list[float]]]):
    """
    @brief Print controller averages.
    @param controller_data:
    """
    print("Controller averages by terrain:")

    for terrain in TERRAIN_ORDER:
        terrain_results: list[tuple[str, float, float]] = []

        for controller_name in CONTROLLER_ORDER:
            terrain_samples = controller_data.get(controller_name, {}).get(terrain, [])

            if not terrain_samples:
                continue

            values = np.asarray(terrain_samples, dtype=float)

            mean_value = float(np.mean(values))
            error_value = (
                float(np.std(values, ddof=1))
                if values.size > 1 else 0.0
            )

            terrain_results.append(
                (controller_name, mean_value, error_value)
            )

        if not terrain_results:
            print(f"  {terrain.value}: no data")
            continue

        winner_name, winner_value, _ = min(
            terrain_results,
            key=lambda item: item[1]
        )

        formatted_results = ", ".join(
            f"{CONTROLLER_LABELS[name]}={mean:.4f} ± {error:.4f}"
            for name, mean, error in terrain_results
        )

        print(
            f"  {terrain.value}: {formatted_results} | "
            f"winner: {CONTROLLER_LABELS[winner_name]} ({winner_value:.4f})"
        )


